"""
ICEFE controller (Tofino 2, BFRT Python) — final version (ICEFE_CNJ_V2).

What this file does when it is loaded with  %run -i ICEFE.py  inside bfrt_python:
  1. enables the three server fiber ports (136, 137, 138) and the INT loop-back port 144;
  2. configures the egress mirror (clone) session used by the classifier;
  3. gives every server port two queues: Q0 = Classic (DWRR weight 1), Q1 = L4S (weight 32);
  4. configures the four low-pass filters (feature EWMAs) for all 8192 flow slots;
  5. loads the 5 random-forest trees (model.json) and the majority vote (majority.txt);
  6. sets the clone (observation) budget of each flow (default: downlink, 52 packets / 13 frames);
  7. resets the coupled AQM probability to 0 on every server port;
  8. installs IPv4/ARP forwarding towards the three servers.
It also defines the helper functions you call afterwards (see "Functions you can call" below).

Functions you can call after loading
  run_coupling_aqm(duration_s=10)   run the coupled DualPI2 AQM loop (None = until Ctrl-C)
  set_coupling_base(port, value)    write the AQM base probability by hand (value/65536)
  set_budget('DL' | 'UL')           clone budget: DL 52 packets/13 frames, UL 32/8
  set_bottleneck(kbps), clear_bottleneck()   shape / unshape Luigi's port 137
  enable_p4tg_ports()               bring up port 152 (P4TG, 100G) for stress tests
  discover_server_ports(), install_discovered_topology()   re-learn the cabling

Files this controller needs in the SAME folder:
  coupling_aqm.py   DualPI2 controller logic (pure Python)
  model.json        thresholds of the 5 trees (generated by the classifier training)
  majority.txt      vote table (5 tree votes -> final class)

Authors: Mateus, Alireza (LERIS). Final version prepared 2026-10-20.
"""

# ---------------------------------------------------------------------------------------
# 0. Settings you may need to change
# ---------------------------------------------------------------------------------------
PROGRAM_NAME = "ICEFE"          # name of the P4 program as loaded by bf_switchd (= ICEFE.p4)

# Coupled AQM (DualPI2, RFC 9332 Appendix A reference parameters).
COUPLING_AQM_ALGORITHM = "DualPI2"   # the only algorithm this P4/controller pair implements
COUPLING_FACTOR = 2                  # L4S probability = 2 x base (fixed in the P4 code)
COUPLING_TARGET_DELAY_MS = 15        # Classic queue delay target
COUPLING_UPDATE_INTERVAL_MS = 16     # the AQM loop runs every 16 ms
COUPLING_MAX_RTT_MS = 100            # documentation only (RFC 9332 sizing)
COUPLING_ALPHA_HZ = 0.16             # PI integral gain
COUPLING_BETA_HZ = 3.2               # PI proportional gain
COUPLING_INITIAL_BASE_PROBABILITY = 0.0   # probability written at load time
COUPLING_STALE_SAMPLE_MS = 64        # a queue with no new sample for 64 ms counts as drained
COUPLING_MAX_POLL_INTERVAL_MS = 32   # stop the loop if BFRT cannot keep the 16 ms schedule

# Feature low-pass filters: one state per flow slot (P4 indexes them by flow-ID bits 12..0).
LPF_SLOTS = 8192
LPF_TIME_CONSTANT_NS = 1000000       # 1 ms gain and decay time constants (SAMPLE mode)

# Clone (observation) budget: a flow is cloned to the classifier while it has sent at most
# 'packets' packets AND fewer than 'frames' RTP frames have completed.
BUDGETS = {'DL': {'packets': 52, 'frames': 13}, 'UL': {'packets': 32, 'frames': 8}}

# ---------------------------------------------------------------------------------------
# 1. Imports and helper module
# ---------------------------------------------------------------------------------------
import json                              # reads model.json
import sys                               # lets us import coupling_aqm.py from this folder
import time                              # timing of the AQM loop
from ipaddress import IPv4Address        # converts "172.16.0.5" to the integer table key
from pathlib import Path                 # file paths

# The folder that holds this file (works with  %run -i /path/ICEFE.py ).
HERE = Path(globals().get("__file__", "ICEFE.py")).resolve().parent
if "bfrt" not in globals():              # this file must run inside bfrt_python
    raise RuntimeError("Run this file inside bfrt_python:  %run -i " + str(HERE / "ICEFE.py"))
if str(HERE) not in sys.path:            # make coupling_aqm.py importable
    sys.path.insert(0, str(HERE))
from coupling_aqm import CouplingAQM, bfrt_field   # DualPI2 core + BFRT field reader

# ---------------------------------------------------------------------------------------
# 2. Testbed description (ports and servers)
# ---------------------------------------------------------------------------------------
FIBER_PORTS = (136, 137, 138)            # Tofino 2 dev ports cabled to the three servers
SERVER_INVENTORY = {                     # management address (SSH) and fiber (data) address
    "Server1": {"management_ip": "0.0.0.0", "fiber_ip": "172.16.0.5"},   # receiver
    "Server2": {"management_ip": "0.0.0.0", "fiber_ip": "172.16.0.6"},   # Classic sender
    "Server3": {"management_ip": "0.0.0.0", "fiber_ip": "172.16.0.4"},   # L4S/replay sender
}
SERVER_PORT_MAP = {"Server1": 137, "Server2": 138, "Server3": 136}   # verified cabling
COUPLING_BASE_BY_PORT = {port: round(COUPLING_INITIAL_BASE_PROBABILITY * 65536)
                         for port in FIBER_PORTS}                    # start value per port

# Handles to the P4 program and the AQM registers (names come from ICEFE.p4).
icefe = getattr(bfrt, PROGRAM_NAME)
coupling_register = icefe.pipe.Egress.coupling_base_probability          # p_base x 65536
coupling_classic_register = icefe.pipe.Egress.coupling_classic_probability  # p_base^2 x 65536
coupling_delay_register = icefe.pipe.Egress.coupling_queue_delay          # last queue delay
coupling_stamp_register = icefe.pipe.Egress.coupling_queue_stamp          # last dequeue time


# ---------------------------------------------------------------------------------------
# 3. Coupled AQM (DualPI2)
# ---------------------------------------------------------------------------------------
def set_coupling_base(dev_port, base_value, verbose=True, pipe=None):
    """Write the AQM base probability p_base = base_value / 65536 for one egress port.

    The P4 program then marks L4S (Q1) packets with probability min(1, 2 x p_base) and
    marks/drops Classic (Q0) packets with probability p_base squared."""
    if type(dev_port) is not int or not 0 <= dev_port < 512:
        raise ValueError("Coupling egress port must be an integer from 0 to 511")
    if type(base_value) is not int or not 0 <= base_value <= 65535:
        raise ValueError("Coupling base threshold must be an integer from 0 to 65535")
    classic_value = (base_value * base_value + 32768) // 65536   # p_base^2, rounded
    if base_value == 65535:                                     # 65535 means "always"
        classic_value = 65535
    target = {} if pipe is None else {"pipe": pipe}
    # Classic first, then base: the two writes are not atomic (a brief mismatch is harmless).
    coupling_classic_register.mod(REGISTER_INDEX=dev_port, f1=classic_value, **target)
    coupling_register.mod(REGISTER_INDEX=dev_port, f1=base_value, **target)
    bfrt.complete_operations()                                  # push both writes now
    coupled_percent = 100 * min(1, 2 * base_value / 65536)
    classic_percent = 100 if classic_value == 65535 else 100 * classic_value / 65536
    if verbose:
        print("Coupling port {}: base={}, Classic CE/drop={:.5f}%, "
              "L4S coupled CE={:.3f}% when TM trigger is inactive".
              format(dev_port, base_value, classic_percent, coupled_percent))


def read_coupling_sample(dev_port, queue):
    """Read the last dequeue delay (ns) and stamp of one queue (index 2 x port + queue)."""
    target = dict(REGISTER_INDEX=2 * dev_port + queue, pipe=dev_port >> 7,
                  from_hw=True, print_ents=False, return_ents=True)
    delay = bfrt_field(coupling_delay_register.get(**target), "f1")   # delay first,
    stamp = bfrt_field(coupling_stamp_register.get(**target), "f1")   # then freshness stamp
    return delay, stamp


def run_coupling_aqm(duration_s=10):
    """Run the DualPI2 feedback loop for duration_s seconds (None = until Ctrl-C).

    Every 16 ms it reads Q0/Q1 delay samples of each server port, updates p_base with the
    PI rule of RFC 9332 and writes it back with set_coupling_base(). It blocks the shell
    while running. The last probabilities stay active when it stops."""
    if duration_s is not None and duration_s <= 0:
        raise ValueError("duration_s must be positive or None")
    if COUPLING_FACTOR != 2 or COUPLING_AQM_ALGORITHM != "DualPI2":
        raise ValueError("This P4/controller combination requires DualPI2 with k=2")
    interval = COUPLING_UPDATE_INTERVAL_MS / 1000
    max_interval = COUPLING_MAX_POLL_INTERVAL_MS / 1000
    controllers = {}
    for port in COUPLING_BASE_BY_PORT:              # one PI controller per egress port
        entry = coupling_register.get(REGISTER_INDEX=port, pipe=port >> 7,
                                      from_hw=True, print_ents=False, return_ents=True)
        base = bfrt_field(entry, "f1")              # continue from the current register value
        controllers[port] = CouplingAQM(
            target_ms=COUPLING_TARGET_DELAY_MS, interval_ms=COUPLING_UPDATE_INTERVAL_MS,
            alpha_hz=COUPLING_ALPHA_HZ, beta_hz=COUPLING_BETA_HZ,
            initial_probability=1.0 if base == 65535 else base / 65536,
            stale_ms=COUPLING_STALE_SAMPLE_MS)
    started = time.monotonic()
    deadline = started
    last_cycle = None
    last_report = started - 1
    cycles = writes = 0
    statuses = {}
    max_observed_interval = 0.0
    print("DualPI2 feedback starting; Ctrl-C stops it and preserves the last probabilities.")
    try:
        while duration_s is None or time.monotonic() - started < duration_s:
            now = time.monotonic()
            if now < deadline:                       # wait for the next 16 ms slot
                time.sleep(deadline - now)
            cycle_started = time.monotonic()
            if duration_s is not None and cycle_started - started >= duration_s:
                break
            if last_cycle is not None:               # refuse to run on a broken schedule
                gap = cycle_started - last_cycle
                max_observed_interval = max(max_observed_interval, gap)
                if gap > max_interval:
                    raise RuntimeError("BFRT polling exceeded {} ms; feedback stopped".
                                       format(COUPLING_MAX_POLL_INTERVAL_MS))
            last_cycle = cycle_started
            samples = {port: (read_coupling_sample(port, 0),      # Q0 (Classic)
                              read_coupling_sample(port, 1))      # Q1 (L4S)
                       for port in controllers}
            sampled_at = time.monotonic()
            if sampled_at - cycle_started > max_interval:
                raise RuntimeError("BFRT sample reads exceeded the polling budget")
            for port, controller in controllers.items():           # PI update per port
                threshold, status = controller.update(*samples[port], sampled_at)
                statuses[port] = status
                if threshold is not None:
                    set_coupling_base(port, threshold, verbose=False, pipe=port >> 7)
                    writes += 1
            if time.monotonic() - cycle_started > max_interval:
                raise RuntimeError("BFRT read/write cycle exceeded the polling budget")
            cycles += 1
            if sampled_at - last_report >= 1:                       # status about once per second
                print("DualPI2 cycle {}: {}".format(cycles, {
                    port: {"state": statuses[port], "p_base": round(c.probability, 6),
                           "queues": c.queue_status(sampled_at)}
                    for port, c in controllers.items()}))
                last_report = sampled_at
            deadline = max(deadline + interval, time.monotonic())   # no catch-up bursts
    except KeyboardInterrupt:
        print("DualPI2 feedback stopped by user.")
    finally:
        print("DualPI2 stopped: cycles={}, updates={}, max interval={:.3f} ms; "
              "last register values remain active".
              format(cycles, writes, max_observed_interval * 1000))
    return {"cycles": cycles, "updates": writes,
            "max_interval_ms": max_observed_interval * 1000, "states": statuses}


# ---------------------------------------------------------------------------------------
# 4. Topology helpers (which server is on which port)
# ---------------------------------------------------------------------------------------
def discover_server_ports():
    """Return the ingress port on which each server's IPv4/ARP traffic was last seen."""
    observations = {}
    for name, server in SERVER_INVENTORY.items():
        host_slot = int(IPv4Address(server["fiber_ip"])) & 7       # register slot = last 3 bits
        entry = icefe.pipe.Ingress.topology_source_port.get(
            REGISTER_INDEX=host_slot, pipe=1, from_hw=True, print_ents=False, return_ents=True)
        observed = bfrt_field(entry, "f1")
        observations[name] = observed if observed in FIBER_PORTS else None
    print("Observed server ingress ports:", observations)
    return observations


def install_server_topology(port_map):
    """Forward IPv4 and ARP traffic for each server's fiber address to its port."""
    if set(port_map) != set(SERVER_INVENTORY):
        raise ValueError("Provide a port for each of Server1, Server2 and Server3")
    if any(type(port) is not int for port in port_map.values()) or set(port_map.values()) != set(FIBER_PORTS):
        raise ValueError("Server mapping must use ports 136, 137, 138 exactly once")
    forwarding = icefe.pipe.Ingress.topology_forward
    forwarding.clear()                                   # replace the three entries
    for name, server in SERVER_INVENTORY.items():
        forwarding.add_with_topology_set_port(
            topology_destination=int(IPv4Address(server["fiber_ip"])),   # destination IP
            port=port_map[name])                                         # -> egress port
    bfrt.complete_operations()
    SERVER_PORT_MAP.update(port_map)
    print("Installed IPv4/ARP server forwarding:", SERVER_PORT_MAP)


def install_discovered_topology():
    """Learn the cabling from live traffic (every server must send IPv4/ARP first)."""
    first = discover_server_ports()
    time.sleep(0.1)
    second = discover_server_ports()
    if first != second:
        raise ValueError("Observed topology changed; verify the fiber cables")
    install_server_topology(second)


def configure_server_queues():
    """Give each server port two queues: Q0 Classic (DWRR weight 1), Q1 L4S (weight 32)."""
    for port in FIBER_PORTS:
        entry = bfrt.tf2.tm.port.cfg.get(dev_port=port, print_ents=False, return_ents=True)
        if isinstance(entry, (list, tuple)):
            if len(entry) != 1:
                raise ValueError("Expected one TM port configuration")
            entry = entry[0]
        data = {(key.decode() if isinstance(key, bytes) else key): value
                for key, value in entry.data.items()}
        queues = data["egress_qid_queues"]               # physical queue numbers of the port
        if int(data["port_queues_count"]) < 2 or len(queues) < 2 or queues[0] == queues[1]:
            raise ValueError("Port {} needs distinct Q0/Q1 queue carving".format(port))
        for logical, weight in ((0, 1), (1, 32)):        # Q0 weight 1, Q1 weight 32
            bfrt.tf2.tm.queue.sched_cfg.mod(
                pipe=port >> 7, pg_id=data["pg_id"], pg_queue=queues[logical], dwrr_weight=weight)
        print("Port {}: Q0={}, Q1={}, PG={}".format(port, queues[0], queues[1], data["pg_id"]))


# ---------------------------------------------------------------------------------------
# 5. Experiment helpers (budget, bottleneck, P4TG port)
# ---------------------------------------------------------------------------------------
def set_budget(direction):
    """Clone budget per flow: 'DL' = 52 packets / 13 frames, 'UL' = 32 packets / 8 frames."""
    budget = BUDGETS[direction]
    table = icefe.pipe.Egress.c7_budget
    table.clear()
    # One range entry: packet index 1..P and completed-frame count 0..F-1 -> clone.
    table.add_with_decisionMirror(c7_pkt_idx_start=1, c7_pkt_idx_end=budget['packets'],
                                  c7_frm_idx_start=0, c7_frm_idx_end=budget['frames'] - 1)
    bfrt.complete_operations()
    print('c7 budget', direction, budget)
    return budget


def set_bottleneck(rate_kbps=1000000, burst_bytes=9000, port=137):
    """Shape an egress port (default: Luigi's port 137 to 1 Gbit/s) to create a bottleneck."""
    bfrt.tf2.tm.port.sched_cfg.mod(dev_port=port, max_rate_enable=True)
    bfrt.tf2.tm.port.sched_shaping.mod(dev_port=port, unit='BPS', provisioning='MIN_ERROR',
                                       max_rate=rate_kbps, max_burst_size=burst_bytes)
    print('c7 bottleneck port', port, rate_kbps, 'kbit/s burst', burst_bytes, 'B')


def clear_bottleneck(port=137):
    """Remove the shaping of an egress port (back to the 10G line rate)."""
    bfrt.tf2.tm.port.sched_cfg.mod(dev_port=port, max_rate_enable=False)
    print('c7 bottleneck cleared on port', port)


def enable_p4tg_ports(ports=(152,)):
    """Bring up the P4TG stress port (Tofino 1 port 30 -> Tofino 2 port 152, 100G DAC).

    ICEFE.p4 forwards everything that enters on 152 to port 137 (superluigi)."""
    for port in ports:
        current = bfrt.port.port.get(DEV_PORT=port, print_ents=False, return_ents=True)
        if current not in (None, -1, []):
            bfrt.port.port.delete(DEV_PORT=port)          # remove a 10G configuration if present
        bfrt.port.port.add(DEV_PORT=port, SPEED="BF_SPEED_100G", FEC="BF_FEC_TYP_NONE",
                           PORT_ENABLE=True)
    print('c7 P4TG ports enabled', ports)


# =======================================================================================
# CONFIGURATION — everything below runs once when the file is loaded
# =======================================================================================

# 6. Ports: enable the server fiber ports (10G, no FEC, auto-negotiation off).
for fiber_port in FIBER_PORTS:
    current = bfrt.port.port.get(DEV_PORT=fiber_port, print_ents=False, return_ents=True)
    if current is None or current == -1 or current == []:          # not configured yet
        bfrt.port.port.add(DEV_PORT=fiber_port, SPEED="BF_SPEED_10G", FEC="BF_FEC_TYP_NONE",
                           PORT_ENABLE=True, AUTO_NEGOTIATION="PM_AN_FORCE_DISABLE")
    else:                                                           # already there: just enable
        bfrt.port.port.mod(DEV_PORT=fiber_port, PORT_ENABLE=True)

# Port 144 in MAC loop-back: INT probes make an extra pass through the switch on it.
bfrt.port.port.add(DEV_PORT=144, SPEED="BF_SPEED_10G", FEC="BF_FEC_TYP_NONE")
bfrt.port.port.mod(DEV_PORT=144, LOOPBACK_MODE='BF_LPBK_MAC_NEAR')

# 7. Clone session 1: egress clones go to port 128 (internal mirror port) and come back to
#    the ingress classifier. 256 B is needed: 48 B clones are too short to be parsed.
bfrt.mirror.cfg.entry_with_normal(sid=1, direction='EGRESS', session_enable=True,
                                  ucast_egress_port=128, ucast_egress_port_valid=True,
                                  max_pkt_len=256).push()

# 8. Traffic Manager: allow per-port shaping (no rate is set here) and carve Q0/Q1.
bfrt.tf2.tm.port.sched_cfg.mod(dev_port=136, max_rate_enable=True)
bfrt.tf2.tm.port.sched_cfg.mod(dev_port=137, max_rate_enable=True)
bfrt.tf2.tm.port.sched_cfg.mod(dev_port=138, max_rate_enable=True)
configure_server_queues()

# 9. Feature low-pass filters (packet size, frame size, inter-packet gap, inter-frame gap):
#    one state per flow slot, SAMPLE mode, 1 ms time constants.
for slot in range(LPF_SLOTS):
    icefe.pipe.Ingress.lpf_packet_size.add(slot, 'SAMPLE', LPF_TIME_CONSTANT_NS, LPF_TIME_CONSTANT_NS, 0)
for slot in range(LPF_SLOTS):
    icefe.pipe.Ingress.lpf_frame_size.add(slot, 'SAMPLE', LPF_TIME_CONSTANT_NS, LPF_TIME_CONSTANT_NS, 0)
for slot in range(LPF_SLOTS):
    icefe.pipe.Ingress.lpf_ipg.add(slot, 'SAMPLE', LPF_TIME_CONSTANT_NS, LPF_TIME_CONSTANT_NS, 0)
for slot in range(LPF_SLOTS):
    icefe.pipe.Ingress.lpf_ifg.add(slot, 'SAMPLE', LPF_TIME_CONSTANT_NS, LPF_TIME_CONSTANT_NS, 0)

# 10. Random forest: 5 trees of range tables, loaded from model.json.
#     Each table matches one feature against ranges; a range gives either a class
#     (1 AR, 2 CG, 3 Other) or a "go to the next table" code (see ICEFE.p4, ingress apply).
#     Units: PS / FS bytes; IPG / IFG in 4.096 us units (bits 31..12 of the ns value).
#     (table name, action, key field, tree, feature) in the order the tables are loaded:
TREE_TABLES = [
    ('table_T1_FS',  'add_with_classify_T1', 'metadata_frame_size',  'Tree1', 'FS'),
    ('table_T1_PS',  'add_with_classify_T1', 'metadata_packet_size', 'Tree1', 'PS'),
    ('table_T1_IPG', 'add_with_classify_T1', 'metadata_ipg_20lsb',   'Tree1', 'IPG'),
    ('table_T2_IFG', 'add_with_classify_T2', 'metadata_ifg_20lsb',   'Tree2', 'IFG'),
    ('table_T2_IPG', 'add_with_classify_T2', 'metadata_ipg_20lsb',   'Tree2', 'IPG'),
    ('table_T3_FS',  'add_with_classify_T3', 'metadata_frame_size',  'Tree3', 'FS'),
    ('table_T3_IFG', 'add_with_classify_T3', 'metadata_ifg_20lsb',   'Tree3', 'IFG'),
    ('table_T3_IPG', 'add_with_classify_T3', 'metadata_ipg_20lsb',   'Tree3', 'IPG'),
    ('table_T4_IFG', 'add_with_classify_T4', 'metadata_ifg_20lsb',   'Tree4', 'IFG'),
    ('table_T4_FS',  'add_with_classify_T4', 'metadata_frame_size',  'Tree4', 'FS'),
    ('table_T4_IPG', 'add_with_classify_T4', 'metadata_ipg_20lsb',   'Tree4', 'IPG'),
    ('table_T5_FS',  'add_with_classify_T5', 'metadata_frame_size',  'Tree5', 'FS'),
    ('table_T5_IPG', 'add_with_classify_T5', 'metadata_ipg_20lsb',   'Tree5', 'IPG'),
]
with (HERE / "model.json").open() as f:
    weights = json.load(f)
for table_name, action, key, tree, feature in TREE_TABLES:
    add = getattr(getattr(icefe.pipe.Ingress, table_name), action)
    for r in sorted(weights[tree][feature], key=lambda k: int(k[1:])):     # r1, r2, ...
        rng = weights[tree][feature][r]
        add(**{key + '_start': rng['min'], key + '_end': rng['max'],
               'classify_result': rng['class']})

# 11. Default clone budget (downlink).
set_budget('DL')

# 12. Majority vote: one exact entry per combination of the 5 tree votes.
with (HERE / "majority.txt").open() as f:
    for line in f:
        line = line.strip()
        if not line:
            continue
        votes = {k.strip(): int(v) for k, v in (part.split('=') for part in line.split(','))}
        icefe.pipe.Ingress.table_majority.add_with_trees_aggregation(
            metadata_classT1=votes['t1'], metadata_classT2=votes['t2'],
            metadata_classT3=votes['t3'], metadata_classT4=votes['t4'],
            metadata_classT5=votes['t5'], majority=votes['m'])

# 13. Start every server port with AQM probability 0 (no coupled marking yet).
for coupling_port, coupling_base_value in COUPLING_BASE_BY_PORT.items():
    set_coupling_base(coupling_port, coupling_base_value)

# 14. Forwarding towards the servers.
if all(port is not None for port in SERVER_PORT_MAP.values()):
    install_server_topology(SERVER_PORT_MAP)
else:
    print("Fiber mapping is unset. Generate IPv4/ARP traffic from all three servers,")
    print("then run discover_server_ports() and install_discovered_topology().")
